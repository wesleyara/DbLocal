import { describe, expect, it } from 'vitest'
import { alterTableSql, createTableSql, draftFromTable, isSafeFragment, newTableDraft, scriptOf, validateDraft, type TableDraft } from './ddl'
import type { SchemaColumn, SchemaTable } from './types/db'

const col = (name: string, nativeType: string, extra: Partial<SchemaColumn> = {}): SchemaColumn => ({
  name,
  nativeType,
  kind: 'string',
  nullable: true,
  default: null,
  isGenerated: false,
  isPrimaryKey: false,
  comment: null,
  enumValues: null,
  ...extra,
})

const users: SchemaTable = {
  name: 'users',
  kind: 'table',
  columns: [
    col('id', 'bigint', { nullable: false, isPrimaryKey: true, isGenerated: true, identity: true }),
    col('name', 'text', { nullable: false }),
    col('role', 'text', { default: "'user'" }),
  ],
  primaryKey: ['id'],
  foreignKeys: [],
  indexes: [{ name: 'users_name_key', columns: ['name'], unique: true, primary: false }],
  implicitRowid: false,
  rowEstimate: null,
  comment: null,
}

const edit = (fn: (d: TableDraft) => void): TableDraft => {
  const d = draftFromTable(users)
  fn(d)
  return d
}

describe('createTableSql', () => {
  const draft: TableDraft = {
    ...newTableDraft('postgres'),
    name: 'orders',
    columns: [
      ...newTableDraft('postgres').columns,
      { from: null, name: 'user_id', type: 'bigint', nullable: false, default: null, identity: false, computed: false, comment: null, onUpdate: null },
      { from: null, name: 'note', type: 'text', nullable: true, default: "'none'", identity: false, computed: false, comment: null, onUpdate: null },
    ],
    indexes: [{ from: null, name: 'orders_note_idx', columns: ['note'], unique: false }],
    foreignKeys: [{ from: null, name: 'orders_user_id_fkey', columns: ['user_id'], refTable: 'users', refColumns: ['id'], onDelete: 'cascade', onUpdate: 'no action' }],
  }

  it('writes Postgres with an identity key, constraints and indexes', () => {
    expect(createTableSql('postgres', 'public', draft)).toEqual([
      `CREATE TABLE "public"."orders" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "user_id" bigint NOT NULL,\n  "note" text DEFAULT 'none',\n  PRIMARY KEY ("id"),\n  CONSTRAINT "orders_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "public"."users" ("id") ON DELETE CASCADE ON UPDATE NO ACTION\n);`,
      'CREATE INDEX "orders_note_idx" ON "public"."orders" ("note");',
    ])
  })

  it('writes MySQL with AUTO_INCREMENT and SQLite with the rowid alias', () => {
    expect(createTableSql('mysql', 'app', { ...draft, foreignKeys: [], indexes: [] })[0]).toContain('`id` bigint NOT NULL AUTO_INCREMENT')
    const sqlite = createTableSql('sqlite', 'main', { ...draft, columns: [{ ...draft.columns[0]!, type: 'INTEGER' }, ...draft.columns.slice(1)] })
    expect(sqlite[0]).toContain('"id" INTEGER PRIMARY KEY,')
    expect(sqlite[0]).not.toContain('PRIMARY KEY ("id")')
    expect(sqlite[0]).toContain('REFERENCES "users" ("id")')
    expect(sqlite[1]).toBe('CREATE INDEX "main"."orders_note_idx" ON "orders" ("note");')
  })
})

describe('alterTableSql', () => {
  it('renames, changes and adds columns on Postgres, in a transaction', () => {
    const draft = edit((d) => {
      d.columns[1]!.name = 'full_name'
      d.columns[2]!.nullable = false
      d.columns[2]!.default = null
      d.columns[2]!.type = 'varchar(20)'
      d.columns.push({ from: null, name: 'age', type: 'integer', nullable: true, default: '0', identity: false, computed: false, comment: null, onUpdate: null })
    })
    const ddl = alterTableSql('postgres', 'public', users, draft)
    expect(ddl.statements).toEqual([
      'ALTER TABLE "public"."users" RENAME COLUMN "name" TO "full_name";',
      'ALTER TABLE "public"."users" ALTER COLUMN "role" TYPE varchar(20) USING "role"::varchar(20);',
      'ALTER TABLE "public"."users" ALTER COLUMN "role" SET NOT NULL;',
      'ALTER TABLE "public"."users" ALTER COLUMN "role" DROP DEFAULT;',
      'ALTER TABLE "public"."users" ADD COLUMN "age" integer DEFAULT 0;',
    ])
    expect(scriptOf('postgres', ddl).split('\n').at(0)).toBe('BEGIN;')
  })

  it('drops indexes, constraints and columns before adding new ones', () => {
    const draft = edit((d) => {
      d.indexes = [{ from: null, name: 'users_role_idx', columns: ['role'], unique: false }]
      d.columns = d.columns.filter((c) => c.name !== 'role').concat({ ...d.columns[2]!, from: null, name: 'kind' })
      d.indexes[0]!.columns = ['kind']
    })
    expect(alterTableSql('postgres', 'public', users, draft).statements).toEqual([
      'ALTER TABLE "public"."users" DROP CONSTRAINT IF EXISTS "users_name_key";',
      'DROP INDEX IF EXISTS "public"."users_name_key";',
      'ALTER TABLE "public"."users" DROP COLUMN "role";',
      'ALTER TABLE "public"."users" ADD COLUMN "kind" text DEFAULT \'user\';',
      'CREATE INDEX "users_role_idx" ON "public"."users" ("kind");',
    ])
  })

  it('restates the whole column with MODIFY on MySQL, keeping identity and ON UPDATE', () => {
    const table: SchemaTable = {
      ...users,
      columns: [...users.columns, col('seen', 'datetime(3)', { default: 'CURRENT_TIMESTAMP(3)', onUpdate: 'CURRENT_TIMESTAMP(3)', comment: "it's" })],
    }
    const d = draftFromTable(table)
    d.columns[3]!.nullable = false
    d.name = 'people'
    expect(alterTableSql('mysql', 'app', table, d).statements).toEqual([
      'RENAME TABLE `app`.`users` TO `app`.`people`;',
      'UPDATE `app`.`people` SET `seen` = CURRENT_TIMESTAMP(3) WHERE `seen` IS NULL;',
      "ALTER TABLE `app`.`people` MODIFY COLUMN `seen` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT 'it''s';",
    ])
  })

  it('uses plain ALTER TABLE on SQLite when it can, and rebuilds the table otherwise', () => {
    const renamed = edit((d) => {
      d.columns[2]!.name = 'kind'
    })
    expect(alterTableSql('sqlite', 'main', users, renamed)).toEqual({
      statements: ['ALTER TABLE "main"."users" RENAME COLUMN "role" TO "kind";'],
      rebuild: false,
    })
    const retyped = edit((d) => {
      d.columns[2]!.nullable = false
    })
    const ddl = alterTableSql('sqlite', 'main', users, retyped, ['CREATE TRIGGER t AFTER INSERT ON users BEGIN SELECT 1; END'])
    expect(ddl.rebuild).toBe(true)
    expect(ddl.statements[0]).toBe('PRAGMA foreign_keys = OFF;')
    // role becomes NOT NULL and has a default: its NULL rows take the default on the way.
    expect(ddl.statements).toContain(
      `INSERT INTO "main"."users__dblocal_new" ("id", "name", "role") SELECT "id", "name", coalesce("role", 'user') FROM "main"."users";`,
    )
    expect(ddl.statements).toContain('CREATE TRIGGER t AFTER INSERT ON users BEGIN SELECT 1; END;')
    expect(scriptOf('sqlite', ddl)).not.toMatch(/^BEGIN;\nPRAGMA/)
  })

  it('returns nothing when nothing changed', () => {
    expect(alterTableSql('postgres', 'public', users, draftFromTable(users)).statements).toEqual([])
    expect(scriptOf('postgres', { statements: [], rebuild: false })).toBe('')
  })
})

describe('validation', () => {
  it('reports names, duplicates, unsafe fragments and unknown index columns', () => {
    const draft = edit((d) => {
      d.name = ' '
      d.columns[1]!.name = 'ID'
      d.columns[2]!.type = 'text; drop table x'
      d.indexes[0]!.columns = ['missing']
    })
    expect(validateDraft(draft)).toEqual([
      { code: 'tableName' },
      { code: 'duplicateColumn', column: 'ID' },
      { code: 'type', column: 'role' },
      { code: 'unknownColumn', name: 'users_name_key', column: 'missing' },
    ])
  })

  it('accepts quotes and parentheses but not statement breaks or comments', () => {
    expect(isSafeFragment("enum('a;b','c')")).toBe(true)
    expect(isSafeFragment('now()')).toBe(true)
    expect(isSafeFragment("'x' -- y")).toBe(false)
    expect(isSafeFragment("'open")).toBe(false)
  })
})
