import { describe, expect, it } from 'vitest'
import { definitionSql, enumTypesSql, insertSql, sequenceResetSql, sqlLiteral, stripDefiner, tableDdl, tableOrder, viewSql } from './dump-sql'
import type { SchemaColumn, SchemaTable } from './types/db'

const col = (name: string, extra: Partial<SchemaColumn> = {}): SchemaColumn => ({
  name,
  nativeType: 'text',
  kind: 'string',
  nullable: true,
  default: null,
  isGenerated: false,
  isPrimaryKey: false,
  comment: null,
  enumValues: null,
  ...extra,
})

const table = (name: string, extra: Partial<SchemaTable> = {}): SchemaTable => ({
  name,
  kind: 'table',
  columns: [col('id', { nativeType: 'integer', kind: 'number', nullable: false, isPrimaryKey: true })],
  primaryKey: ['id'],
  foreignKeys: [],
  indexes: [],
  implicitRowid: false,
  rowEstimate: null,
  comment: null,
  ...extra,
})

const fk = (refTable: string) => ({ name: `fk_${refTable}`, columns: ['ref'], refSchema: null, refTable, refColumns: ['id'], onDelete: 'no action' as const, onUpdate: 'no action' as const })

describe('dump sql', () => {
  it('orders parents before children and survives cycles and self references', () => {
    const order = tableOrder([table('items', { foreignKeys: [fk('orders')] }), table('orders', { foreignKeys: [fk('users'), fk('orders')] }), table('users')])
    expect(order.map((t) => t.name)).toEqual(['users', 'orders', 'items'])
    const cycle = tableOrder([table('a', { foreignKeys: [fk('b')] }), table('b', { foreignKeys: [fk('a')] })])
    expect(cycle.map((t) => t.name).sort()).toEqual(['a', 'b'])
  })

  it('writes literals per dialect', () => {
    const text = col('t')
    expect(sqlLiteral('postgres', "it's", text)).toBe("'it''s'")
    expect(sqlLiteral('mysql', 'a\\b', text)).toBe("'a\\\\b'")
    expect(sqlLiteral('postgres', true, text)).toBe('TRUE')
    expect(sqlLiteral('mysql', false, text)).toBe('0')
    expect(sqlLiteral('sqlite', 12n, text)).toBe('12')
    expect(sqlLiteral('postgres', Buffer.from([1, 255]), text)).toBe("'\\x01ff'::bytea")
    expect(sqlLiteral('mysql', Buffer.from([1, 255]), text)).toBe("X'01ff'")
    const at = new Date('2024-05-06T07:08:09.010Z')
    expect(sqlLiteral('mysql', at, col('d', { kind: 'datetime' }))).toBe("'2024-05-06 07:08:09.010'")
    expect(sqlLiteral('postgres', at, col('d', { kind: 'datetime' }))).toBe("'2024-05-06T07:08:09.010Z'")
    expect(sqlLiteral('mysql', at, col('d', { kind: 'date' }))).toBe("'2024-05-06'")
    expect(sqlLiteral('postgres', { a: 1 }, col('j', { kind: 'json' }))).toBe('\'{"a":1}\'')
    expect(sqlLiteral('postgres', ['x', null, 'y"z'], col('a', { kind: 'array' }))).toBe('\'{"x",NULL,"y\\"z"}\'')
    expect(sqlLiteral('sqlite', null, text)).toBe('NULL')
  })

  it('builds schema-free DDL with foreign keys after the data on Postgres and MySQL', () => {
    const items = table('items', {
      columns: [col('id', { nativeType: 'integer', kind: 'number', nullable: false, isPrimaryKey: true, default: "nextval('items_id_seq'::regclass)" }), col('ref')],
      foreignKeys: [fk('orders')],
    })
    const pg = tableDdl('postgres', items)
    expect(pg.create[0]).toContain('CREATE TABLE "items"')
    expect(pg.create[0]).toContain('GENERATED BY DEFAULT AS IDENTITY')
    expect(pg.create[0]).not.toContain('nextval')
    expect(pg.foreignKeys[0]).toMatch(/^ALTER TABLE "items" ADD CONSTRAINT "fk_orders" FOREIGN KEY \("ref"\) REFERENCES "orders"/)
    expect(sequenceResetSql('postgres', items)[0]).toContain(`pg_get_serial_sequence('"items"', 'id')`)
    const sqlite = tableDdl('sqlite', items)
    expect(sqlite.foreignKeys).toEqual([])
    expect(sqlite.create[0]).toContain('FOREIGN KEY ("ref") REFERENCES "orders"')
    const auto = tableDdl('sqlite', table('t', { indexes: [{ name: 'sqlite_autoindex_t_1', columns: ['id'], unique: true, primary: false }] }))
    expect(auto.create[1]).toBe('CREATE UNIQUE INDEX "t_id_key" ON "t" ("id");')
  })

  it('writes multi-row inserts and enum types', () => {
    const t = table('t', { columns: [col('id', { kind: 'number' }), col('name')] })
    expect(insertSql('mysql', t, t.columns, [{ id: 1, name: 'a' }, { id: 2, name: null }])).toBe('INSERT INTO `t` (`id`, `name`) VALUES\n  (1, \'a\'),\n  (2, NULL);')
    const e = table('u', { columns: [col('role', { kind: 'enum', nativeType: 'user_role', enumValues: ['a', "b'c"] })] })
    expect(enumTypesSql([e, e])).toEqual(["CREATE TYPE user_role AS ENUM ('a', 'b''c');"])
  })

  it('cleans routine, trigger and view definitions', () => {
    expect(stripDefiner('CREATE DEFINER=`root`@`%` TRIGGER t BEFORE UPDATE ON p')).toBe('CREATE TRIGGER t BEFORE UPDATE ON p')
    expect(definitionSql('postgres', 'CREATE TRIGGER t BEFORE UPDATE ON public.p FOR EACH ROW EXECUTE FUNCTION public.f()', 'public')).toBe(
      'CREATE TRIGGER t BEFORE UPDATE ON p FOR EACH ROW EXECUTE FUNCTION f();',
    )
    expect(definitionSql('postgres', 'CREATE OR REPLACE FUNCTION public.f() RETURNS int AS $$ select 1 $$ LANGUAGE sql\n', 'public')).toBe(
      'CREATE OR REPLACE FUNCTION f() RETURNS int AS $$ select 1 $$ LANGUAGE sql;',
    )
    expect(viewSql('postgres', 'v', ' SELECT 1;')).toBe('CREATE VIEW "v" AS\nSELECT 1;')
    expect(viewSql('sqlite', 'v', 'CREATE VIEW v AS SELECT 1')).toBe('CREATE VIEW v AS SELECT 1;')
  })
})
